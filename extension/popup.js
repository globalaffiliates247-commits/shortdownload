// TAIO Cookie Exporter - Core Logic
let currentUrl = '';
let currentHost = '';
let cachedCookies = [];

// Trích xuất domain gốc (vd: www.youtube.com -> youtube.com)
function getBaseDomain(hostname) {
  if (!hostname) return '';
  const parts = hostname.split('.');
  if (parts.length >= 2) {
    return parts.slice(-2).join('.');
  }
  return hostname;
}

// Chuyển đổi mảng cookies sang định dạng Netscape HTTP Cookie File
function convertToNetscape(cookies) {
  let output = "# Netscape HTTP Cookie File\n";
  output += "# https://curl.se/docs/http-cookies.html\n";
  output += "# Generated by TAIO Cookie Exporter\n";
  output += `# Exported at: ${new Date().toISOString()}\n\n`;

  for (const c of cookies) {
    let domain = c.domain || '';
    // Chuẩn Netscape: nếu áp dụng cho subdomain thì bắt đầu bằng dấu chấm
    const includeSubdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const path = c.path || '/';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    // Hạn dùng cookie (nếu session cookie thì gán 1 năm từ bây giờ)
    const expiration = c.expirationDate 
      ? Math.round(c.expirationDate) 
      : Math.round(Date.now() / 1000) + 31536000;
    const name = c.name || '';
    const value = c.value || '';

    output += `${domain}\t${includeSubdomains}\t${path}\t${secure}\t${expiration}\t${name}\t${value}\n`;
  }
  return output;
}

// Hiển thị thông báo trạng thái
function showToast(msg, isSuccess = true) {
  const toast = document.getElementById('statusToast');
  toast.innerText = msg;
  toast.className = `status-toast ${isSuccess ? 'success' : 'error'}`;
  setTimeout(() => {
    toast.className = 'status-toast';
  }, 3500);
}

// Tải danh sách cookies của tab hiện tại
async function loadCookies() {
  try {
    const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (!tab || !tab.url) {
      document.getElementById('domainVal').innerText = 'Không phát hiện tab';
      return;
    }

    currentUrl = tab.url;
    const urlObj = new URL(tab.url);
    currentHost = urlObj.hostname;
    document.getElementById('domainVal').innerText = currentHost;

    const baseDomain = getBaseDomain(currentHost);

    // Lấy tất cả cookies từ trình duyệt
    const allCookies = await chrome.cookies.getAll({});
    
    // Lọc cookies liên quan đến domain hiện tại
    const isDomainOnly = document.getElementById('currentDomainOnly').checked;
    if (isDomainOnly) {
      cachedCookies = allCookies.filter(c => {
        const d = (c.domain || '').replace(/^\./, '').toLowerCase();
        return d.endsWith(baseDomain.toLowerCase()) || d === currentHost.toLowerCase();
      });
    } else {
      cachedCookies = allCookies;
    }

    document.getElementById('cookieCount').innerText = `${cachedCookies.length} cookies`;
  } catch (err) {
    console.error('Lỗi khi nạp cookies:', err);
    document.getElementById('domainVal').innerText = 'Lỗi truy cập';
    showToast('Không thể đọc cookies tab hiện tại', false);
  }
}

// Tải file cookies.txt về máy
function handleDownload() {
  if (!cachedCookies || cachedCookies.length === 0) {
    showToast('Không có cookies nào để xuất!', false);
    return;
  }

  const netscapeText = convertToNetscape(cachedCookies);
  const blob = new Blob([netscapeText], { type: 'text/plain;charset=utf-8' });
  const downloadUrl = URL.createObjectURL(blob);
  
  const a = document.createElement('a');
  a.href = downloadUrl;
  const baseDomain = getBaseDomain(currentHost) || 'cookies';
  a.download = `cookies_${baseDomain}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(downloadUrl);

  showToast(`✅ Đã tải ${cachedCookies.length} cookies thành công!`);
}

// Sao chép nội dung cookies vào clipboard
async function handleCopy() {
  if (!cachedCookies || cachedCookies.length === 0) {
    showToast('Không có cookies nào để sao chép!', false);
    return;
  }

  const netscapeText = convertToNetscape(cachedCookies);
  try {
    await navigator.clipboard.writeText(netscapeText);
    showToast(`📋 Đã sao chép ${cachedCookies.length} cookies vào Clipboard!`);
  } catch (err) {
    showToast('Không thể truy cập Clipboard', false);
  }
}

document.addEventListener('DOMContentLoaded', () => {
  loadCookies();

  document.getElementById('currentDomainOnly').addEventListener('change', () => {
    loadCookies();
  });

  document.getElementById('btnDownload').addEventListener('click', handleDownload);
  document.getElementById('btnCopy').addEventListener('click', handleCopy);
});
